// The assistant's instructions. Kept server-side and rebuilt per request so
// the signed-in/out half is stated as fact rather than something the model has
// to infer from which tools happen to exist.
//
// Note what this is NOT doing: it isn't the security boundary. Anything here
// is advisory — a determined prompt injection can talk the model out of it.
// The real guarantees are structural: citizen tools are absent from the
// toolset when signed out (buildTools), no tool accepts a user identifier, and
// the gateway test runs in the browser behind an explicit confirmation.

// What the route resolved about the page the user is on. A catalog entry
// carries the name from OUR data, never anything the client sent — see
// resolvePageContext.
export type PromptPageContext =
  | { kind: "catalog"; identifier: string; name: string }
  | { kind: "usage" }
  | { kind: "profile" }
  | { kind: "dashboard" }
  | { kind: "projects" };

function whereTheUserIs(pageContext: PromptPageContext): string[] {
  switch (pageContext.kind) {
    case "catalog":
      return [
        "## Where the user is",
        "",
        `They have the documentation for **${pageContext.name}** (identifier \`${pageContext.identifier}\`)`,
        "open in front of them right now.",
        "",
        "- Resolve a bare \"this API\", \"this one\", \"it\" or \"this endpoint\" to that API. Don't ask",
        "  which one they mean when the answer is on their screen.",
        "- If they name a DIFFERENT API, follow the name — they've moved on, and the page is only",
        "  where they happen to be standing.",
        "- Still call getApiCatalog/getApiEndpoint for the actual content. Knowing which API they",
        "  mean is not knowing what it says.",
      ];
    case "usage":
      return [
        "## Where the user is",
        "",
        "They are looking at their gateway usage log, so a question about \"these calls\", \"this",
        "error\" or \"why is it failing\" is about their own recent requests — getMyUsage.",
      ];
    case "profile":
      return ["## Where the user is", "", "They are on their profile page."];
    case "dashboard":
      return ["## Where the user is", "", "They are on their developer dashboard."];
    case "projects":
      return [
        "## Where the user is",
        "",
        "They are looking at projects, so \"this project\", \"mine\" or \"why isn't it showing\"",
        "is about an entry rather than an API. Use getMyProjects for their own entries and",
        "listShowcaseProjects for the public catalogue — which one depends on whether they mean",
        "theirs or everyone's.",
      ];
  }
}

